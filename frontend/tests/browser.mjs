// Optional browser regression checks. Requires Playwright and Chromium; see docs/validacion.md.
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const recorded = JSON.parse(fs.readFileSync(process.env.INTEGRATION_FIXTURE || '/tmp/cve-intelligence-integration.json', 'utf8'))
const fixture = recorded.cases.find(c => c.status === 200 && c.body.sources.length).body
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/api/health', route => route.fulfill({ json: recorded.health }))
const requests = []
let failNext = false
await page.route('**/api/chat', async route => {
  const body = route.request().postDataJSON(); requests.push(body)
  await new Promise(resolve => setTimeout(resolve, 250))
  if (failNext) { failNext = false; return route.fulfill({ status: 503, json: { message: 'Fallo de prueba', request_id: 'ui-error' } }) }
  await route.fulfill({ json: { ...fixture, conversation_id: body.conversation_id } })
})
await page.goto('http://127.0.0.1:5173')
const ipInput = page.getByRole('textbox', { name: 'Coloca la IP objetivo' })
await ipInput.fill('999.168.1.10')
await page.getByRole('button', { name: /Detectar/ }).click()
await page.getByRole('alert').waitFor()
await ipInput.fill('192.168.1.10')
await page.getByRole('button', { name: /Detectar/ }).click()
await page.locator('.finding-results').waitFor({ timeout: 15000 })
assert.equal(await page.locator('.finding-card').count(), 3)
assert.ok(await page.getByText(/no comprueba el objetivo/).isVisible())
await page.getByRole('button', { name: /CVE-2021-41773/ }).click()
await page.getByRole('button', { name: '¿Cuál es el impacto?' }).click()
await page.getByText(/Referencia ilustrativa:/).waitFor()
await page.getByRole('button', { name: '¿Cómo valido este hallazgo?' }).click()
await page.getByText(/no ejecuta comprobaciones reales/).waitFor()
assert.equal(requests.length, 0, 'Detection simulation must not call the RAG API')
await page.getByRole('button', { name: /Volver a Detección/ }).click()
await page.getByRole('button', { name: /Consultas/ }).click()
const input = page.getByRole('textbox', { name: 'Tu consulta' })
await input.fill('What is CVE-2023-27849?')
await input.press('Shift+Enter')
assert.ok((await input.inputValue()).endsWith('\n'))
await input.press('Enter')
await page.getByRole('button', { name: 'Ver evidencia' }).waitFor()
assert.equal(requests.length, 1)
await page.getByRole('button', { name: 'Ver evidencia' }).click()
assert.ok(await page.getByText(fixture.request_id, { exact: true }).isVisible())
await page.getByRole('button', { name: 'Copiar respuesta' }).click()
await page.getByText('Copiado', { exact: true }).waitFor()
await page.screenshot({ path: `${process.env.SCREENSHOT_DIR || '/tmp'}/cve-desktop.png`, fullPage: true })
failNext = true
await input.fill('Failed question')
await input.press('Enter')
await page.getByRole('button', { name: 'Reintentar' }).waitFor()
await input.fill('Later question')
await input.press('Enter')
await page.waitForFunction(() => document.querySelectorAll('.answer-footer').length === 2)
await page.getByRole('button', { name: 'Reintentar' }).click()
await page.waitForFunction(() => document.querySelectorAll('.answer-footer').length === 3)
assert.equal(requests.at(-1).message, 'Failed question')
assert.ok(await page.getByText('Later question', { exact: true }).isVisible())
await page.reload()
assert.equal(await page.locator('.answer-footer').count(), 3)
await page.setViewportSize({ width: 390, height: 844 })
const openHistory = page.getByRole('button', { name: 'Abrir historial' })
await openHistory.click()
await page.getByRole('dialog', { name: 'Historial de conversaciones' }).waitFor()
await page.keyboard.press('Escape')
assert.equal(await openHistory.evaluate(el => el === document.activeElement), true)
await page.getByRole('button', { name: 'Evidencia', exact: true }).click()
await page.getByRole('dialog', { name: 'Evidencia de la respuesta' }).waitFor()
await page.keyboard.press('Escape')
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
await page.screenshot({ path: `${process.env.SCREENSHOT_DIR || '/tmp'}/cve-mobile.png`, fullPage: true })
await page.evaluate(() => localStorage.setItem('cve-intelligence-conversations-v1', '[null]'))
await page.reload()
await page.getByText(/No se pudo leer el historial local/).waitFor()
assert.deepEqual(errors, [])
console.log('Browser checks passed: simulated detection validation, findings and no-RAG boundary; chat send, evidence, retry, persistence, mobile panels, focus, overflow, no JS errors.')
await browser.close()
